PRE_DELAY = 0.25   # silence before voice in each scene
POST_PAD = 0.85    # breathing room after voice


async def gen(scene_id: str, text: str) -> str:
    path = os.path.join(AUDIO_DIR, f"{scene_id}.mp3")
    communicate = edge_tts.Communicate(text, VOICE, rate=RATE)
    await communicate.save(path)
    return path


def probe_duration(path: str) -> float:
    out = subprocess.check_output([
        "ffprobe", "-v", "quiet", "-show_entries", "format=duration",
        "-of", "csv=p=0", path]).decode().strip()
    return float(out)


async def main():
    only = sys.argv[1] if len(sys.argv) > 1 else None
    timing_path = os.path.join(ROOT, "src", "timing.json")
    existing = {"scenes": {}}
    if os.path.exists(timing_path):
        existing = json.load(open(timing_path))
    scenes = existing.get("scenes", {})
    for sid, text, captions in SCENES:
        if only and sid != only:
            continue
        path = await gen(sid, text)
        dur = probe_duration(path)
        total = dur + PRE_DELAY + POST_PAD
        frames = int(round(total * FPS))
        scenes[sid] = {
            "audio": f"audio/{sid}.mp3",
            "voiceSec": round(dur, 3),
            "preDelay": PRE_DELAY,
            "frames": frames,
            "captions": captions,
        }
        print(f"{sid}: voice={dur:.2f}s frames={frames}")
    os.makedirs(os.path.join(ROOT, "src"), exist_ok=True)
    json.dump({"fps": FPS, "scenes": scenes}, open(timing_path, "w"),
              ensure_ascii=False, indent=2)
    print("wrote", timing_path)


if __name__ == "__main__":
    asyncio.run(main())
